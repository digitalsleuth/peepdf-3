    app.setWindowIcon(QIcon(icon))

    window = MainWindow()
    window.show()
    if len(sys.argv) > 1:
        window.open_file(sys.argv[1])
    exitCode = app.exec()
    gc.freeze()
    sys.exit(exitCode)


